def _current_age(today: date) -> int:
    age = today.year - _BIRTH_DATE.year
    if (today.month, today.day) < (_BIRTH_DATE.month, _BIRTH_DATE.day):
        age -= 1
    return age


def get_text() -> str:
    today = datetime.now(_KST).date()
    return _TEMPLATE.format(age=_current_age(today))
